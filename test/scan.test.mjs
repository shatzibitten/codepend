test('Claude: only origin.kind === "human" counts as a typed prompt', () => {
  const s = parseLines('claude', [
    claudeHuman('2026-07-01T10:00:00.000Z', 'сделай сборку и проверь, что всё работает'),
    // 94 % of `user` lines look like this — tool output, no origin at all.
    j({
      type: 'user',
      timestamp: '2026-07-01T10:00:05.000Z',
      message: {
        role: 'user',
        content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'ok' }],
      },
    }),
    // injected background-task chatter
    j({
      type: 'user',
      timestamp: '2026-07-01T10:00:06.000Z',
      origin: { kind: 'task-notification' },
      message: { role: 'user', content: '<task-notification>done</task-notification>' },
    }),
    // isMeta plumbing
    j({
      type: 'user',
      timestamp: '2026-07-01T10:00:07.000Z',
      isMeta: true,
      origin: { kind: 'human' },
      message: { role: 'user', content: 'Caveat: the messages below were generated by…' },
    }),
    // array content: only `text` blocks are the human's words
    claudeHuman('2026-07-01T10:01:00.000Z', [
      { type: 'text', text: 'and now ship it' },
      { type: 'image', source: { type: 'base64', data: 'iVBOR' } },
    ]),
  ]);

  assert.equal(s.counts.humanTurns, 2);
  assert.deepEqual(
    s.humanTurns.map((t) => t.text),
    ['сделай сборку и проверь, что всё работает', 'and now ship it'],
  );
  assert.equal(s.humanTurns[0].words, 7, 'Cyrillic words counted correctly');
  assert.equal(s.humanTurns[0].ts, T('2026-07-01T10:00:00.000Z'));
});

test('Claude: queue-operation enqueues are a fallback, never a second count', () => {
  const dup = 'исправь баг с таймером';
  const s = parseLines('claude', [
    // A queued prompt that the user really did send → must NOT be counted twice.
    j({
      type: 'queue-operation',
      operation: 'enqueue',
      timestamp: '2026-07-01T09:59:00.000Z',
      content: dup,
    }),
    claudeHuman('2026-07-01T10:00:00.000Z', dup),
    // A queued prompt that never became a user line → counts once.
    j({
      type: 'queue-operation',
      operation: 'enqueue',
      timestamp: '2026-07-01T10:02:00.000Z',
      content: 'Удали и сделай улучшенную копию, только намного лучше',
    }),
    // Injected notification that happens to travel through the queue → never a prompt.
    j({
      type: 'queue-operation',
      operation: 'enqueue',
      timestamp: '2026-07-01T10:03:00.000Z',
      content: '<task-notification>\n<task-id>bg0w8g1r6</task-id>\n</task-notification>',
    }),
    // Typed, then deleted before sending. Not a turn — but we keep it for its own detector.
    j({
      type: 'queue-operation',
      operation: 'remove',
      timestamp: '2026-07-01T10:04:00.000Z',
      content: 'до твоих правок такого не было',
    }),
    j({ type: 'queue-operation', operation: 'dequeue', timestamp: '2026-07-01T10:05:00.000Z' }),
  ]);

  assert.equal(s.counts.humanTurns, 2);
  assert.deepEqual(
    s.humanTurns.map((t) => t.text),
    [dup, 'Удали и сделай улучшенную копию, только намного лучше'],
    'sorted by ts, deduped against the real user line',
  );
  assert.equal(s.unsent.length, 1);
  assert.equal(s.unsent[0].text, 'до твоих правок такого не было');
});

