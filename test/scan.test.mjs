test('wordCount is Unicode-aware (Cyrillic counts as words, not bytes)', () => {
  const ru = 'Удали и сделай улучшенную копию, только намного лучше';
  assert.equal(ru.length, 53);          // 53 code points…
  assert.equal(Buffer.byteLength(ru), 98); // …but 98 bytes. Never count bytes.
  assert.equal(wordCount(ru), 8);
  assert.equal(wordCount('hello world'), 2);
  assert.equal(wordCount(''), 0);
  assert.equal(wordCount('emoji 🚀 don’t break it'), 4); // don’t = one token
});

