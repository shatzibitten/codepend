test('extractCodexPrompt: unwraps IDE context, drops machine wrappers, keeps prose', () => {
  // The single highest-risk case: 351 of 1000 real prompts arrive wrapped like this. Dropping
  // everything that starts with '#' would delete a third of the user's words.
  const wrapped =
    '# Context from my IDE setup:\n\n## Open tabs:\n- plan.md: .cursor/plans/plan.md\n\n' +
    '## My request for Codex:\nразбери план и дай критику';
  assert.equal(extractCodexPrompt(wrapped), 'разбери план и дай критику');

  assert.equal(
    extractCodexPrompt('# Chrome tabs:\n- tab\n\n## My request for Codex:\nsummarise this page'),
    'summarise this page',
  );
  assert.equal(
    extractCodexPrompt(
      '<in-app-browser-context source="ambient-tab">…</in-app-browser-context>\n' +
        '## My request for Codex:\nчто тут написано?',
    ),
    'что тут написано?',
  );

  // AGENTS.md injection — machine-authored, never a prompt.
  assert.equal(
    extractCodexPrompt(
      '# AGENTS.md instructions for /Users/me/dev\n\n<INSTRUCTIONS>\n# Agent rules\n</INSTRUCTIONS>',
    ),
    null,
  );
  // <app-context> / <environment_context> / <turn_aborted> / <heartbeat> style blocks.
  assert.equal(extractCodexPrompt('<app-context>\n  <cwd>/Users/me</cwd>\n</app-context>'), null);
  assert.equal(
    extractCodexPrompt('<turn_aborted>\nThe user interrupted the previous turn on purpose.'),
    null,
  );
  assert.equal(extractCodexPrompt('<heartbeat>ping</heartbeat>'), null);
  assert.equal(extractCodexPrompt('<environment_context>\n  <shell>zsh</shell>'), null);

  // A pasted spec really does start with '#'. It is the user's own text — keep it.
  const spec = '# Спецификация — главное меню v3\n\n## Концепция одной строкой\nЖивая сцена.';
  assert.equal(extractCodexPrompt(spec), spec);

  assert.equal(extractCodexPrompt('   '), null);
  assert.equal(extractCodexPrompt(undefined), null);
});

