test('durationMs sums active bursts and ignores the "laptop was closed" gaps', () => {
  const ev = (ts) => codexEvent(ts, { type: 'agent_message', message: 'ok' });
  const s = parseLines('codex', [
    codexMeta({}, '2026-08-01T10:00:00.000Z'),
    ev('2026-08-01T10:00:00.000Z'),
    ev('2026-08-01T10:00:30.000Z'), // +30 s   → counts
    ev('2026-08-01T10:05:00.000Z'), // +4.5 m  → counts
    ev('2026-08-04T10:05:00.000Z'), // +3 days → ignored entirely
    ev('2026-08-04T10:06:00.000Z'), // +60 s   → counts
  ]);
  assert.equal(s.durationMs, 30_000 + 270_000 + 60_000);
  assert.ok(s.spanMs > 3 * 24 * 3600 * 1000, 'the naive span is 64× bigger — never use it');
  assert.equal(s.startedAt, T('2026-08-01T10:00:00.000Z'));
  assert.equal(s.endedAt, T('2026-08-04T10:06:00.000Z'));
  assert.ok(IDLE_GAP_MS === 600_000);
});

