test('scan(): a line larger than the read chunk is reassembled, not corrupted', async (t) => {
  // Real records reach 2.9 MB; the read buffer is 4 MB. A 6 MB line proves the carry path
  // across multiple chunk boundaries, which is where a hand-rolled line splitter goes wrong.
  const root = await mkdtemp(path.join(os.tmpdir(), 'codepend-big-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const day = path.join(root, 'codex', 'sessions', '2026', '08', '05');
  await mkdir(day, { recursive: true });
  const huge = 'ы'.repeat(3_000_000); // 3 M code points → 6 MB of UTF-8
  await writeFile(
    path.join(day, 'rollout-2026-08-05T10-00-00-019f-root.jsonl'),
    [
      codexMeta(),
      codexEvent('2026-08-05T05:01:00.000Z', { type: 'agent_message', message: huge }),
      codexEvent('2026-08-05T05:01:10.000Z', { type: 'user_message', message: 'после большого' }),
    ].join('\n') + '\n',
  );

  const [s] = await scan({
    claudeDir: '/nonexistent',
    codexDir: path.join(root, 'codex'),
    cache: false,
  });
  assert.equal(s.counts.agentTurns, 1);
  assert.equal(s.agentTurns[0].chars, 3_000_000, 'the whole line survived the chunk boundaries');
  assert.equal(s.agentTurns[0].text.length, 800, 'stored text is capped');
  assert.equal(s.humanTurns[0].text, 'после большого', 'the line after it still parses');
});

